"""Study courses: concepts, verbatim passages, and free / MC / image-occlusion questions.

A Study course (the Study tab: closed-book questions graded by Jev, typed
cards, image-occlusion labels) lives in ONE pack that the app serves, and that
pack is GENERATED by builder scripts and gitignored — nothing an author could
edit. So the MCP keeps a contributor's course as its own tracked source set:

    study-courses/<course>/course.json   course, sections, sources, concepts,
                                         passages, questions, diagrams
    study-courses/<course>/sources/      the files passages are quoted from
    study-courses/<course>/images/       the pictures of its occlusion cards

`study_check` merges it into a copy of the pack and runs the pack's own rules
(scripts/study_course.py, under the content python: pydantic + Pillow);
`study_apply` writes the merge into the live pack (private repo only — the
course kit sends the folder as a pull request).

Every id is namespaced by the course (`<course>.<id>`, diagrams `<course>-<id>`),
so a contributor course can never overwrite a concept it did not write. The
author writes content; the boilerplate the pack model demands (aliases, intro,
option ids, constraint ids, card ids, colours) is filled in here.
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from . import paths

COURSE_RE = re.compile(r"^[a-z][a-z0-9]*(-[a-z0-9]+)*$")
LOCAL_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
# A pid's local part: words joined by "-", segments by "." (passage ids are
# <concept>.p1). No "/" and no empty segment, so never a path step.
PID_LOCAL_RE = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*(\.[a-z0-9]+(-[a-z0-9]+)*)*")
FORMATS = ("free", "mc", "label", "card")
KINDS = ("content", "evaluative", "relation", "check")
SOURCE_EXT = {".md", ".txt", ".html", ".htm"}
PALETTE = ["#2563EB", "#16A34A", "#DC2626", "#9333EA", "#EA580C", "#0891B2", "#CA8A04", "#DB2777"]


def folder(course: str) -> Path:
    # Every op names its course; refuse anything that is not an id, so
    # "../x" can never read or write outside study-courses/.
    if not COURSE_RE.fullmatch(str(course or "")):
        raise ValueError(f"course id '{course}': lowercase letters/digits and dashes, e.g. 'ap-bio-genetics'.")
    return paths.STUDY_COURSES / course


def load(course: str) -> dict:
    f = folder(course) / "course.json"
    if not f.exists():
        known = list_courses()["courses"]
        raise ValueError(f"No Study course '{course}'. Known: {', '.join(c['course'] for c in known) or 'none'}"
                         " — make one with study_course_create.")
    return json.loads(f.read_text(encoding="utf-8"))


def save(course: str, spec: dict) -> None:
    f = folder(course) / "course.json"
    tmp = f.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    tmp.replace(f)


def pid(course: str, local: str) -> str:
    """`<course>.<local>`. An id already carrying the prefix is left alone."""
    local = str(local or "").strip().removeprefix(course + ".")
    # 🔴 Checked even when the prefix was given: source_add names a FILE after
    # the local part, so "bio.../../x" must never get through.
    if not PID_LOCAL_RE.fullmatch(local):
        raise ValueError(f"id '{local}' must be lowercase letters/digits joined by '-', e.g. 'mitosis'.")
    return f"{course}.{local}"


def _ref(course: str, ref: str) -> str:
    """A concept reference: a short id is this course's; one with a dot is a full
    pack id (a prerequisite in another course, e.g. 'bioprok.cytoplasm')."""
    ref = str(ref or "").strip()
    return ref if "." in ref else pid(course, ref)


def _upsert(items: list, item: dict, replace: bool, what: str) -> str:
    for i, old in enumerate(items):
        if old["id"] == item["id"]:
            if not replace:
                raise ValueError(f"{what} '{item['id']}' already exists — pass replace=true to rewrite it.")
            items[i] = item
            return "replaced"
    items.append(item)
    return "added"


def list_courses() -> dict:
    out = []
    if paths.STUDY_COURSES.is_dir():
        for f in sorted(paths.STUDY_COURSES.glob("*/course.json")):
            spec = json.loads(f.read_text(encoding="utf-8"))
            qs = spec.get("questions", [])
            out.append({"course": f.parent.name, "title": spec["course"]["title"],
                        "concepts": len(spec.get("concepts", [])),
                        "questions": {fmt: sum(q["format"] == fmt for q in qs) for fmt in FORMATS},
                        "diagrams": len(spec.get("diagrams", []))})
    return {"courses": out, "live_pack": str(paths.study_pack()) if paths.study_pack() else None}


def create(course: str, title: str, sections: list, eyebrow: str = "", public: bool = False,
           language: str = "en") -> dict:
    if language not in ("en", "zh"):
        raise ValueError("language: 'en' (English) or 'zh' (Simplified Chinese).")
    if not COURSE_RE.fullmatch(course or "") or len(course) > 40:
        raise ValueError("course id: lowercase letters/digits and dashes, e.g. 'ap-bio-genetics'.")
    if (folder(course) / "course.json").exists():
        raise ValueError(f"Study course '{course}' already exists.")
    if not sections:
        raise ValueError("Give at least one section: [{id, title}] — the colour-coded parts of the course.")
    secs = []
    for i, s in enumerate(sections):
        s = {"title": s} if isinstance(s, str) else dict(s)
        sid = s.get("id") or re.sub(r"[^a-z0-9]+", "-", s["title"].lower()).strip("-")
        secs.append({"id": pid(course, sid), "title": s["title"].strip(),
                     "color": s.get("color") or PALETTE[i % len(PALETTE)]})
    spec = {"course": {"id": course, "title": title.strip(), "eyebrow": eyebrow, "public": bool(public),
                       **({"language": language} if language != "en" else {})},
            "sections": secs, "sources": [], "concepts": [], "passages": [], "questions": [],
            "diagrams": [], "edges": []}
    for sub in ("sources", "images"):
        (folder(course) / sub).mkdir(parents=True, exist_ok=True)
    save(course, spec)
    return {"course": course, "folder": str(folder(course).relative_to(paths.REPO)),
            "sections": [s["id"] for s in secs],
            "next_steps": ["study_source_add: the text every passage is quoted from (verbatim).",
                           "study_concept_add per idea, prerequisites first.",
                           "study_question_add (free / mc / card) and study_diagram_add (image occlusion).",
                           "study_check until ok, then study_apply (private repo) or a pull request (kit)."]}


def source_add(course: str, source: str, title: str, license: str, text: str | None = None,
               source_path: str | None = None, authors: str = "", year: int = 0,
               url: str | None = None, kind: str = "doc", replace: bool = False) -> dict:
    spec = load(course)
    if bool(text) == bool(source_path):
        raise ValueError("Pass exactly one of text (the source's words) or source_path (a .md/.txt/.html file).")
    if not str(license).strip():
        raise ValueError("license is required: who wrote it and whether it may be republished "
                         "(e.g. 'own notes, CC BY 4.0', 'OpenStax CC BY 4.0'). The kit is PUBLIC — "
                         "never add a teacher's slides or a textbook you may not share.")
    sid = pid(course, source)
    ext = ".md" if text else Path(source_path).suffix.lower()
    if ext not in SOURCE_EXT:
        raise ValueError(f"A source file must be one of {sorted(SOURCE_EXT)} (convert a PDF to text first).")
    dest = folder(course) / "sources" / f"{sid.split('.', 1)[1]}{ext}"
    if not replace and any(s["id"] == sid for s in spec["sources"]):
        raise ValueError(f"source '{sid}' already exists — pass replace=true.")
    if dest.exists() and not replace:
        raise ValueError(f"{dest.name} already exists — pass replace=true.")
    if text:
        dest.write_text(text, encoding="utf-8")
    else:
        shutil.copyfile(Path(source_path).expanduser(), dest)
    entry = {"id": sid, "title": title, "authors": authors, "year": int(year or 0),
             "path": str(dest.relative_to(paths.REPO)), "kind": kind, "license": license}
    if url:
        entry["url"] = url
    action = _upsert(spec["sources"], entry, replace, "source")
    save(course, spec)
    return {"source": sid, "file": entry["path"], "action": action,
            "next_step": "Quote it in study_concept_add passages: [{source, text}] — text copied EXACTLY."}


def _constraints(cid: str, items: list) -> list:
    out = []
    for i, k in enumerate(items, 1):
        k = {"text": k} if isinstance(k, str) else dict(k)
        out.append({"id": k.get("id") or f"{cid}.k{i}", "text": k["text"],
                    "demand": k.get("demand", "explain"), "required": bool(k.get("required", i == 1))})
    return out


def concept_add(course: str, concept: dict, replace: bool = False) -> dict:
    spec = load(course)
    c = dict(concept)
    for key in ("id", "title", "definition", "passages"):
        if not c.get(key):
            raise ValueError(f"A concept needs `{key}`.")
    cid = pid(course, c["id"])
    section = pid(course, c["section"]) if c.get("section") else spec["sections"][0]["id"]
    if section not in {s["id"] for s in spec["sections"]}:
        raise ValueError(f"Unknown section '{c.get('section')}'. Sections: {[s['id'] for s in spec['sections']]}")
    sources = {s["id"] for s in spec["sources"]}
    passage_ids, new_passages = [], []
    reused = {pid(course, x) for x in c["passages"] if isinstance(x, str)}
    n = 0
    for x in c["passages"]:
        if isinstance(x, str):           # an existing passage id
            passage_ids.append(pid(course, x))
            continue
        src = pid(course, x["source"])
        if src not in sources:
            raise ValueError(f"Unknown source '{x['source']}' — add it with study_source_add first.")
        n += 1
        while f"{cid}.p{n}" in reused:   # never mint over a passage reused by id
            n += 1
        p = {"id": f"{cid}.p{n}", "source": src, "locator": x.get("locator") or "", "text": x["text"]}
        new_passages.append(p)
        passage_ids.append(p["id"])
    prereqs = c.get("prereqs") or {}
    if isinstance(prereqs, list):
        prereqs = {k: 1.0 for k in prereqs}
    node = {"id": cid, "title": c["title"].strip(), "kind": c.get("kind", "conceptual"),
            "aliases": c.get("aliases") or [c["title"].strip()],
            "definition": c["definition"], "intro": c.get("intro") or c["definition"],
            "constraints": _constraints(cid, c.get("constraints", [])),
            "misconceptions": [{"id": m.get("id") or f"{cid}.m{i}", "label": m["label"],
                                "description": m["description"]}
                               for i, m in enumerate(c.get("misconceptions", []), 1)],
            "passages": passage_ids,
            "prereqs": {_ref(course, k): float(v) for k, v in prereqs.items()},
            "section": section, "diagrams": [_diagram_id(course, d) for d in c.get("diagrams", [])]}
    action = _upsert(spec["concepts"], node, replace, "concept")
    # Replacing drops the concept's old inline passages, but not one it reuses by id.
    spec["passages"] = [x for x in spec["passages"]
                        if not x["id"].startswith(cid + ".p") or x["id"] in reused] + new_passages
    save(course, spec)
    return {"concept": cid, "action": action, "passages": passage_ids,
            "next_step": "study_question_add: a content question and (conceptual) an evaluative one, "
                         "then study_check. A conceptual concept needs >= 2 constraints."}


def question_add(course: str, questions: list, replace: bool = False) -> dict:
    spec = load(course)
    taken = {q["id"] for q in spec["questions"]}
    n = len(spec["questions"]) + 1
    done = []
    staged = [dict(q) for q in spec["questions"]]
    for raw in questions:
        q = dict(raw)
        fmt = q.get("format", "free")
        if fmt not in FORMATS:
            raise ValueError(f"format must be one of {FORMATS}")
        if fmt == "label":
            raise ValueError("Image-occlusion (label) cards are made by study_diagram_add from the diagram's labels.")
        if not q.get("prompt") or not q.get("targets"):
            raise ValueError("A question needs `prompt` and `targets` (the concept ids it tests).")
        while f"{course}.q{n}" in taken:
            n += 1
        qid = pid(course, q["id"]) if q.get("id") else f"{course}.q{n}"
        taken.add(qid)
        out = {"id": qid, "kind": q.get("kind", "content"), "format": fmt,
               "demand": q.get("demand") or ("explain" if fmt == "free" else "recall"),
               "targets": [_ref(course, t) for t in q["targets"]], "prompt": q["prompt"],
               "reference": q.get("reference", "")}
        if out["kind"] not in KINDS:
            raise ValueError(f"kind must be one of {KINDS}")
        if fmt == "mc":
            opts = q.get("options") or []
            out["options"] = [{"id": chr(97 + i), "text": o["text"], "correct": bool(o.get("correct")),
                               "why": o.get("why") or ("Correct." if o.get("correct") else "Not this one.")}
                              for i, o in enumerate(opts)]
            if not out["reference"]:
                out["reference"] = next((o["text"] for o in opts if o.get("correct")), "")
        for key in ("expected", "required"):
            if q.get(key):
                out[key] = [_ref(course, t) for t in q[key]]
        for key in ("rephrasings", "answers", "group"):
            if q.get(key):
                out[key] = q[key]
        if fmt == "card" and q.get("diagram"):
            out["diagram"] = _diagram_id(course, q["diagram"])
            out["box"] = int(q.get("box", -1))
        _upsert(staged, out, replace, "question")
        done.append(qid)
    spec["questions"] = staged
    save(course, spec)
    return {"added": done, "next_step": "study_check."}


def _diagram_id(course: str, local: str) -> str:
    local = local.removeprefix(course + "-")
    if not LOCAL_RE.fullmatch(local):
        raise ValueError(f"diagram id '{local}' must be lowercase words joined by '-'.")
    return f"{course}-{local}"


def remove(course: str, kind: str, item: str) -> dict:
    spec = load(course)
    key = {"concept": "concepts", "question": "questions", "source": "sources",
           "diagram": "diagrams", "section": "sections"}.get(kind)
    if not key:
        raise ValueError("kind: concept, question, source, diagram or section.")
    full = _diagram_id(course, item) if kind == "diagram" else pid(course, item)
    before = len(spec[key])
    spec[key] = [x for x in spec[key] if x["id"] != full]
    if len(spec[key]) == before:
        raise ValueError(f"No {kind} '{full}'.")
    if kind == "concept":
        spec["passages"] = [x for x in spec["passages"] if not x["id"].startswith(full + ".p")]
    if kind == "diagram":
        spec["questions"] = [q for q in spec["questions"] if q.get("diagram") != full or q["format"] != "label"]
    save(course, spec)
    return {"removed": full, "next_step": "study_check — anything that pointed at it is reported there."}
